const CHAPTER_N = /^第\s*(\d+(?:\.\d+)?)\s*章(?:\s*目錄)?$/;
const DONE_CH = /^完成 · Python 第(\d+)章(?: · 單元(\d+))?$/;

export function pythonEn(zh) {
  if (zh == null) return zh;
  const key = String(zh)
    .replace(/\\n/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (PYTHON_PAGE_EN[key]) return PYTHON_PAGE_EN[key];
  if (PYTHON_PAGE_EN[zh]) return PYTHON_PAGE_EN[zh];
  const ch = key.match(CHAPTER_N);
  if (ch) {
    return key.includes("目錄")
      ? `Chapter ${ch[1]} contents`
      : `Chapter ${ch[1]}`;
  }
  const done = key.match(DONE_CH);
  if (done) {
    return done[2]
      ? `Done · Python Chapter ${done[1]} · part ${done[2]}`
      : `Done · Python Chapter ${done[1]}`;
  }
  return PYTHON_PAGE_EN[key] || PYTHON_QUIZ_EN[key] || PYTHON_QUIZ_EN[zh] || key;
}
