export function getPythonQuiz(chapterId) {
  const quiz = PYTHON_QUIZZES[String(chapterId)] ?? null;
  if (!quiz) return null;
  return {
    ...quiz,
    titleEn: quiz.titleEn || pythonEn(quiz.title),
    questions: quiz.questions.map((q) => ({
      ...q,
      questionEn: q.questionEn || pythonEn(q.question),
      optionsEn: q.optionsEn || q.options.map((option) => pythonEn(option)),
    })),
  };
}
